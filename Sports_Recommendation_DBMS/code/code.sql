-- STEP 5: VIEW — sport_recommendation_view
-- Encapsulates all 7 matching criteria in one place.
-- ════════════════════════════════════════════════════════════

CREATE OR REPLACE VIEW sport_recommendation_view AS
SELECT
    u.user_id,
    u.name,
    s.sport_id,
    s.sport_name,
    s.sport_type,
    s.equipment_required
FROM users u
JOIN physical_traits pt ON pt.user_id = u.user_id
JOIN lifestyle        l  ON l.user_id  = u.user_id
JOIN interests        i  ON i.user_id  = u.user_id
JOIN sports           s
    ON  pt.weight_kg       BETWEEN s.min_weight_kg AND s.max_kg_weight
    AND u.age              BETWEEN s.min_age        AND s.max_age
    AND l.free_time_hours  >= s.min_time_required_hrs
    -- Stamina: user must meet or exceed sport requirement
    AND get_stamina_score(pt.stamina_level) >= get_stamina_score(s.required_stamina)
    -- Team preference must match exactly
    AND i.prefers_team = s.is_team_sport
    -- Indoor/outdoor preference must match sport type
    AND (
        (i.prefers_indoor = 'Yes' AND s.sport_type = 'Indoor')
     OR (i.prefers_indoor = 'No'  AND s.sport_type = 'Outdoor')
    )
    -- Health issue → low-impact sports only
    AND (l.health_issue = 'None' OR s.low_impact = 'Yes');


-- ════════════════════════════════════════════════════════════
-- STEP 6A: PROCEDURE (implicit cursor) — recommend_sports_for_user
-- ════════════════════════════════════════════════════════════

CREATE OR REPLACE PROCEDURE recommend_sports_for_user (
    p_user_id IN NUMBER
) AS
    v_found NUMBER := 0;
BEGIN
    FOR rec IN (
        SELECT sport_name, sport_type, equipment_required
        FROM   sport_recommendation_view
        WHERE  user_id = p_user_id
        ORDER BY sport_name
    ) LOOP
        v_found := 1;
        DBMS_OUTPUT.PUT_LINE(
            'Recommended Sport: ' || rec.sport_name    ||
            ', Type: '            || rec.sport_type    ||
            ', Equipment: '       || rec.equipment_required
        );
    END LOOP;

    IF v_found = 0 THEN
        DBMS_OUTPUT.PUT_LINE('No sports matched for user ID ' || p_user_id);
    END IF;
END;
/


-- ════════════════════════════════════════════════════════════
-- STEP 6B: PROCEDURE (explicit cursor + exception handling)
--          recommend_sports_explicit
-- ════════════════════════════════════════════════════════════

CREATE OR REPLACE PROCEDURE recommend_sports_explicit (
    p_user_id IN NUMBER
) AS
    CURSOR c_sports IS
        SELECT sport_name, sport_type, equipment_required
        FROM   sport_recommendation_view
        WHERE  user_id = p_user_id
        ORDER BY sport_name;

    v_rec   c_sports%ROWTYPE;
    v_found BOOLEAN := FALSE;
    v_name  users.name%TYPE;

BEGIN
    SELECT name INTO v_name FROM users WHERE user_id = p_user_id;

    DBMS_OUTPUT.PUT_LINE('=== Recommendations for: ' || v_name || ' (ID ' || p_user_id || ') ===');

    OPEN c_sports;
    LOOP
        FETCH c_sports INTO v_rec;
        EXIT WHEN c_sports%NOTFOUND;
        v_found := TRUE;
        DBMS_OUTPUT.PUT_LINE(
            '  ► ' || v_rec.sport_name ||
            ' ['   || v_rec.sport_type || ']' ||
            ' | Equipment: ' || v_rec.equipment_required
        );
    END LOOP;
    CLOSE c_sports;

    IF NOT v_found THEN
        DBMS_OUTPUT.PUT_LINE('  No sports matched for this user profile.');
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('ERROR: No user found with ID ' || p_user_id);
    WHEN OTHERS THEN
        IF c_sports%ISOPEN THEN CLOSE c_sports; END IF;
        DBMS_OUTPUT.PUT_LINE('Unexpected error: ' || SQLERRM);
        RAISE;
END recommend_sports_explicit;
/


