-- STEP 1: FUNCTION — get_stamina_score
-- Must be created BEFORE the view that references it.
-- ════════════════════════════════════════════════════════════

CREATE OR REPLACE FUNCTION get_stamina_score (
    p_level IN VARCHAR2
) RETURN NUMBER
IS
BEGIN
    RETURN CASE UPPER(p_level)
               WHEN 'LOW'    THEN 1
               WHEN 'MEDIUM' THEN 2
               WHEN 'HIGH'   THEN 3
               ELSE 0
           END;
END get_stamina_score;
/


